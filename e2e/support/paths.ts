import { mkdirSync, realpathSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Everything an e2e run writes lives in `e2e/tmp/` (git-ignored, or `PROJO_E2E_DIR`): the app
 * bundle, the generated videos and, per browser, a library folder, a staging folder and a data
 * dir. Not the OS temp dir: the test walks the folder explorer from `/`, and macOS's `$TMPDIR`
 * has more entries than the explorer lists (2 000). Real path: the explorer refuses links that
 * leave their directory.
 */
const resolveRoot = (): string => {
  const root = process.env['PROJO_E2E_DIR'] ?? fileURLToPath(new URL('../tmp', import.meta.url))
  mkdirSync(root, { recursive: true })
  return realpathSync(root)
}

export const e2eRoot: string = resolveRoot()

/** Release-like bundle (`server.js` + `public/` + `drizzle/`), built by `scripts/build-app.ts`. */
export const appDir: string = join(e2eRoot, 'app')

/** Videos generated by ffmpeg in the global setup, copied into each browser's folders. */
export const mediaDir: string = join(e2eRoot, 'media')

/** One server per browser, each with a fresh `DATA_DIR`: both run the first-launch wizard. */
export const servers = {
  chromium: { port: 4801 },
  webkit: { port: 4802 },
} as const

export type ServerName = keyof typeof servers

export const isServerName = (value: string): value is ServerName =>
  Object.keys(servers).includes(value)

export const dataDirOf = (name: ServerName): string => join(e2eRoot, `data-${name}`)

/**
 * The "dossier en vrac" a server's admin adds in the wizard. One per browser: a file a journey
 * drops in must not show up in the other browser's catalog.
 */
export const libraryDirOf = (name: ServerName): string => join(e2eRoot, `library-${name}`)

/** Outside the library, same file system: files land in the library by an atomic rename. */
export const incomingDirOf = (name: ServerName): string => join(e2eRoot, `incoming-${name}`)

/** The "Playback" library of the M3 journeys (`playback-library.ts`), one per browser. */
export const playbackDirOf = (name: ServerName): string => join(e2eRoot, `playback-${name}`)

export const baseUrlOf = (name: ServerName): string => `http://127.0.0.1:${servers[name].port}`
