import { mkdirSync, realpathSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Everything an e2e run writes lives in `e2e/tmp/` (git-ignored, or `PROJO_E2E_DIR`): the app
 * bundle, the generated videos, the library folders and the data dir. Not the OS temp dir: the
 * test walks the folder explorer from `/`, and macOS's `$TMPDIR` has more entries than the
 * explorer lists (2 000). Real path: the explorer refuses links that leave their directory.
 */
const resolveRoot = (): string => {
  const root = process.env['PROJO_E2E_DIR'] ?? fileURLToPath(new URL('../tmp', import.meta.url))
  mkdirSync(root, { recursive: true })
  return realpathSync(root)
}

export const e2eRoot: string = resolveRoot()

/** Release-like bundle (`server.js` + `public/` + `drizzle/`), built by `scripts/build-app.ts`. */
export const appDir: string = join(e2eRoot, 'app')

/** Videos generated by ffmpeg in the global setup, copied into the library folders. */
export const mediaDir: string = join(e2eRoot, 'media')

/** The one server of the run, on a fresh `DATA_DIR`: every browser project shares it. */
export const port = 4801

export const baseUrl = `http://127.0.0.1:${port}`

export const dataDir: string = join(e2eRoot, 'data')

/** The "messy folder" the admin adds in the wizard (journey 1). */
export const libraryDir: string = join(e2eRoot, 'library')

/** Outside the library, same file system: files land in the library by an atomic rename. */
export const incomingDir: string = join(e2eRoot, 'incoming')

/** The "Playback" library of the M3 and M4 journeys (`playback-library.ts`). */
export const playbackDir: string = join(e2eRoot, 'playback')
