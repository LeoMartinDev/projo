// Splits each Geist family into two files, written to fonts/ and committed: `core` (Latin, the
// punctuation and the few symbols the apps and the website write) and `rest` (every other
// character of the font), each declared with its unicode-range in fonts/geist.css. A page
// downloads `rest` only if it shows one of its characters (a Cyrillic title, say), so the usual
// page loads half the bytes. The weight axis is cut to the weights the stylesheets use.
// Run after a geist upgrade: bun run --cwd packages/design fonts (fonts.test.ts fails until then).
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

import fontverter from 'fontverter'
import { Blob as HbBlob, Face } from 'harfbuzzjs'
import subsetFont from 'subset-font'

const root = resolve(import.meta.dir, '..')
const geist = resolve(root, 'node_modules/geist')

/** Ranges of `core`: Google Fonts' "latin" subset, plus arrows and comparison signs. */
export const coreRanges: ReadonlyArray<readonly [number, number]> = [
  [0x0000, 0x00ff],
  [0x0131, 0x0131],
  [0x0152, 0x0153],
  [0x02bb, 0x02bc],
  [0x02c6, 0x02c6],
  [0x02da, 0x02da],
  [0x02dc, 0x02dc],
  [0x0304, 0x0304],
  [0x0308, 0x0308],
  [0x0329, 0x0329],
  [0x2000, 0x206f],
  [0x20ac, 0x20ac],
  [0x2122, 0x2122],
  [0x2190, 0x2199],
  [0x2212, 0x2212],
  [0x2215, 0x2215],
  [0x2248, 0x2248],
  [0x2260, 0x2260],
  [0x2264, 0x2265],
  [0xfeff, 0xfeff],
  [0xfffd, 0xfffd],
]

/** The weights the stylesheets set run from 400 to 800 (checked in fonts.test.ts). */
export const weights = { min: 400, max: 800 } as const

export const families = [
  { family: 'Geist', file: 'geist', source: 'dist/fonts/geist-sans/Geist-Variable.woff2' },
  {
    family: 'Geist Mono',
    file: 'geist-mono',
    source: 'dist/fonts/geist-mono/GeistMono-Variable.woff2',
  },
] as const

const inCore = (codePoint: number) =>
  coreRanges.some(([first, last]) => codePoint >= first && codePoint <= last)

const hex = (codePoint: number) => codePoint.toString(16).toUpperCase().padStart(4, '0')

/** `U+0000-00FF, U+0131…` from sorted code points or ranges. */
const unicodeRange = (ranges: ReadonlyArray<readonly [number, number]>) =>
  ranges
    .map(([first, last]) => (first === last ? `U+${hex(first)}` : `U+${hex(first)}-${hex(last)}`))
    .join(', ')

const toRanges = (codePoints: readonly number[]) =>
  codePoints.reduce<Array<[number, number]>>((ranges, codePoint) => {
    const previous = ranges.at(-1)
    if (previous && previous[1] === codePoint - 1) previous[1] = codePoint
    else ranges.push([codePoint, codePoint])
    return ranges
  }, [])

// A Buffer: fontverter sniffs the format with Buffer.toString.
const readSource = (source: string) => readFileSync(resolve(geist, source))

/** Code points of each family, split between `core` and `rest`. One family at a time: the
 * WebAssembly decoders reuse their memory from one call to the next. */
const splitFamilies = async () => {
  const split = []
  for (const family of families) {
    const font = await fontverter.convert(readSource(family.source), 'truetype')
    const codePoints = [...new Face(new HbBlob(font), 0).collectUnicodes()].sort((a, b) => a - b)
    split.push({
      ...family,
      core: codePoints.filter(inCore),
      rest: codePoints.filter((codePoint) => !inCore(codePoint)),
    })
  }
  return split
}

const geistVersion = () =>
  (JSON.parse(readFileSync(resolve(geist, 'package.json'), 'utf8')) as { version: string }).version

const face = (family: string, file: string, range: string) => `@font-face {
  font-family: '${family}';
  src: url('./${file}.woff2') format('woff2');
  font-weight: ${weights.min} ${weights.max};
  font-style: normal;
  font-display: swap;
  unicode-range: ${range};
}
`

/** fonts/geist.css, as the installed geist gives it. */
export const geistCss = async () => {
  const faces = (await splitFamilies()).map(({ family, file, rest }) =>
    [
      face(family, `${file}-core`, unicodeRange(coreRanges)),
      face(family, `${file}-rest`, unicodeRange(toRanges(rest))),
    ].join('\n'),
  )
  return `/* Generated by scripts/fonts.ts from geist ${geistVersion()}: do not edit (fonts.css imports it). */

${faces.join('\n')}`
}

if (import.meta.main) {
  for (const { file, source, core, rest } of await splitFamilies()) {
    for (const [part, codePoints] of [
      ['core', core],
      ['rest', rest],
    ] as const) {
      const subset = await subsetFont(readSource(source), String.fromCodePoint(...codePoints), {
        targetFormat: 'woff2',
        variationAxes: { wght: weights },
      })
      await Bun.write(resolve(root, `fonts/${file}-${part}.woff2`), subset)
      console.log(`fonts/${file}-${part}.woff2: ${codePoints.length} characters, ${subset.length} B`)
    }
  }
  await Bun.write(resolve(root, 'fonts/geist.css'), await geistCss())
}
